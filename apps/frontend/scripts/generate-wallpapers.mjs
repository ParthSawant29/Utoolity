import {readdir,writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const dir=path.join(root,"public/wallpapers");
const imgs=new Set([".avif",".jpeg",".jpg",".png",".webp"]), vids=new Set([".mp4",".webm",".ogv",".mov"]);
const pretty=s=>s.replace(/\.[^.]+$/,"").replace(/[-_]+/g," ").replace(/\b\w/g,c=>c.toUpperCase());
const url=(...p)=>"/"+["wallpapers",...p].map(encodeURIComponent).join("/");
const entries=(await readdir(dir,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name));
const all=[];
for(const e of entries){
 if(e.isDirectory()){
  const files=(await readdir(path.join(dir,e.name),{withFileTypes:true})).filter(x=>x.isFile()).map(x=>x.name).sort();
  if(e.name.toLowerCase()==="live"){for(const f of files)if(vids.has(path.extname(f).toLowerCase()))all.push({id:e.name+"/"+f,name:pretty(f),kind:"live",url:url(e.name,f)});continue;}
  const list=files.filter(f=>imgs.has(path.extname(f).toLowerCase()));if(!list.length)continue;
  const find=v=>list.find(f=>new RegExp("^"+v+"\\.(avif|jpe?g|png|webp)$","i").test(f));
  const light=find("light")??list[0],dark=find("dark")??light;
  all.push({id:e.name,name:pretty(e.name),kind:"image",url:url(e.name,light),darkUrl:url(e.name,dark),lightUrl:url(e.name,light)});
 }else if(imgs.has(path.extname(e.name).toLowerCase())){const u=url(e.name);all.push({id:e.name,name:pretty(e.name),kind:"image",url:u,darkUrl:u,lightUrl:u});}
}
const images=all.filter(w=>w.kind==="image"),fallback=images.find(w=>w.id.toLowerCase()==="default")??images[0]??all[0];
const content='// Generated by scripts/generate-wallpapers.mjs. Do not edit.\nimport type { Wallpaper } from "./wallpapers";\nexport const GENERATED_WALLPAPERS: readonly Wallpaper[] = '+JSON.stringify(all,null,2)+';\nexport const GENERATED_DEFAULT_WALLPAPER_ID = '+JSON.stringify(fallback?.id??"Default")+';\n';
await writeFile(path.join(root,"lib/wallpapers.generated.ts"),content);
console.log("Generated "+all.length+" wallpapers.");